 f=440*2**((midi-69)/12); n=int(RATE*duration); values=[]
 for i in range(n):
  t=i/RATE; attack=min(1,t/.012); release=min(1,(duration-t)/.065)
  if kind=='pure': v=math.sin(2*math.pi*f*t)*.34*attack*release
  else:
   v=sum(a*math.sin(2*math.pi*f*h*t)*math.exp(-t*(1.7+h*.16)) for h,a in [(1,.50),(2,.20),(3,.11),(4,.045),(5,.025)])*attack*release
  values.append(v)
 return values

